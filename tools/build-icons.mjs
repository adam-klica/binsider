// Writes brand icon paths (Simple Icons, CC0) to plugin/binsider-core/includes/icons.php.
//   node tools/build-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as si from 'simple-icons';

const dest = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'plugin', 'binsider-core', 'includes', 'icons.php');
const names = ['siWhatsapp', 'siViber', 'siFacebook', 'siInstagram', 'siYoutube', 'siX', 'siTiktok', 'siTelegram'];

let php = "<?php\n/**\n * Brand icon paths (24x24) from Simple Icons (CC0). Generated by tools/build-icons.mjs — do not edit.\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nfunction binsider_icon_paths(): array {\n\treturn array(\n";
for (const name of names) php += `\t\t'${name.slice(2).toLowerCase()}' => '${si[name].path}',\n`;
php += '\t);\n}\n';
fs.writeFileSync(dest, php);
console.log('icons:', names.length);
